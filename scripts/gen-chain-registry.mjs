#!/usr/bin/env node
/**
 * gen-chain-registry.mjs — emit the server's copy of the chain table.
 *
 * The native-wallet purchase path needs, per chain: which RPC to verify a
 * transaction against, how many confirmations to wait for, the native token's
 * decimals, and what that token is worth in USD. All of that already exists in
 * src/lib/blockchain/config.js, which is the single source of truth for chains.
 * Generating from it means adding a chain stays a one-file change.
 *
 *   node scripts/gen-chain-registry.mjs
 *
 * Writes server/chain_registry.py. Re-run after editing config.js.
 *
 * ── The one thing that is NOT in config.js ────────────────────────────────────
 * CoinGecko ids. They cannot be derived from a ticker, and getting one wrong
 * misprices real money — every id in COINGECKO_IDS below was checked against
 * https://api.coingecko.com/api/v3/coins/markets on 2026-08-14 by confirming
 * the returned name and homepage, not by pattern-matching the symbol. Three
 * would have been wrong on a guess:
 *
 *   beam      → 'beam-2', NOT 'beam'. 'beam' is Beam Mimblewimble (beam.mw),
 *               an unrelated privacy coin that happens to share the ticker.
 *               It trades ~6x higher, so a guess overcharges every Beam buyer.
 *   polygon   → 'polygon-ecosystem-token' (POL), NOT 'matic-network'. MATIC
 *               migrated to POL; CoinGecko still lists both, ~42% apart, so
 *               the wrong one undercharges every Polygon buyer by ~42%.
 *               config.js was still saying symbol MATIC while being priced as
 *               POL — corrected to POL there too, so the quote names the token
 *               the wallet actually sends.
 *   ton       → 'the-open-network' is correct even though it now returns symbol
 *               GRAM: Toncoin was renamed Gram. Verified via homepage ton.org.
 *
 * If you add a chain, verify its id the same way. Do not guess.
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { CHAINS } = await import(resolve(ROOT, 'src/lib/blockchain/config.js'))

// Verified 2026-08-14 — see the header before changing any of these.
const COINGECKO_IDS = {
  ETH:   'ethereum',
  POL:   'polygon-ecosystem-token',
  AVAX:  'avalanche-2',
  RON:   'ronin',
  BNB:   'binancecoin',
  MNT:   'mantle',
  RBTC:  'rootstock',
  FLR:   'flare-networks',
  CELO:  'celo',
  GLMR:  'moonbeam',
  BEAM:  'beam-2',
  OAS:   'oasys',
  HBAR:  'hedera-hashgraph',
  INJ:   'injective-protocol',
  FLOW:  'flow',
  SOL:   'solana',
  TON:   'the-open-network',
  APT:   'aptos',
  SUI:   'sui',
  STRK:  'starknet',
  ADA:   'cardano',
  NEAR:  'near',
  XLM:   'stellar',
  ALGO:  'algorand',
  EGLD:  'elrond-erd-2',
  XRD:   'radix',
  XTZ:   'tezos',
}

const rows = []
const skipped = []

for (const c of Object.values(CHAINS)) {
  if (c.testnet) continue

  const cg = COINGECKO_IDS[c.nativeCurrency.symbol] ?? null

  // A chain can be live and still not sell tiles for its native token.
  let payable = true
  let why = ''
  if (c.gasless) { payable = false; why = 'gasless chain — sFUEL is a valueless faucet token, there is nothing to charge' }
  else if (c.halted) { payable = false; why = 'chain halted in config.js' }
  else if (!cg) { payable = false; why = `no verified CoinGecko id for ${c.nativeCurrency.symbol}` }

  if (!payable) skipped.push(`${c.key} (${why})`)

  rows.push(`    "${c.key}": Chain(
        key="${c.key}",
        name=${JSON.stringify(c.name)},
        family="${c.family}",
        chain_id=${c.id === null || c.id === undefined ? 'None' : typeof c.id === 'number' ? c.id : JSON.stringify(c.id)},
        rpc_url=${JSON.stringify(c.rpcUrl)},
        rpc_fallback=${c.rpcUrlFallback ? JSON.stringify(c.rpcUrlFallback) : 'None'},
        confirmations=${c.confirmations ?? 1},
        symbol=${JSON.stringify(c.nativeCurrency.symbol)},
        decimals=${c.nativeCurrency.decimals},
        coingecko_id=${cg ? JSON.stringify(cg) : 'None'},
        native_pay=${payable ? 'True' : 'False'},
        native_pay_note=${JSON.stringify(why)},
        explorer_tx=${JSON.stringify((c.explorerUrl ?? '') + (c.explorerTxPath ?? '/tx/'))},
    ),`)
}

const py = `"""
chain_registry.py — the chains the server can verify a payment on.

GENERATED by scripts/gen-chain-registry.mjs from src/lib/blockchain/config.js.
Do not edit by hand; add the chain in config.js and re-run the generator.

\`native_pay\` is False where a chain cannot sell a tile for its own token —
SKALE's sFUEL is a valueless faucet token, and a halted chain should not take
money. Those chains still work; they just show the off-chain payment rail only.
"""
from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class Chain:
    key: str
    name: str
    family: str
    chain_id: Optional[int]
    rpc_url: str
    rpc_fallback: Optional[str]
    confirmations: int
    symbol: str
    decimals: int
    coingecko_id: Optional[str]
    native_pay: bool
    native_pay_note: str
    explorer_tx: str

    @property
    def rpcs(self):
        """Primary first, then fallback. Public RPCs rot; always try both."""
        return [u for u in (self.rpc_url, self.rpc_fallback) if u]


CHAINS = {
${rows.join('\n')}
}

# Canonical name -> key, for the \`chain\` column written on the blocks row.
BY_NAME = {c.name.lower(): c.key for c in CHAINS.values()}


def get_chain(key_or_name: str):
    """Look a chain up by key ('base') or canonical name ('Base'). None if unknown."""
    if not key_or_name:
        return None
    k = str(key_or_name).strip().lower()
    if k in CHAINS:
        return CHAINS[k]
    return CHAINS.get(BY_NAME.get(k, ""), None)


def payable_chains():
    return {k: c for k, c in CHAINS.items() if c.native_pay}
`

writeFileSync(resolve(ROOT, 'server/chain_registry.py'), py)

const payable = rows.length - skipped.length
console.log(`✓ server/chain_registry.py — ${rows.length} mainnet chains, ${payable} accept native payment`)
if (skipped.length) console.log('  no native pay:\n    ' + skipped.join('\n    '))
