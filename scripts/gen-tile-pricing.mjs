#!/usr/bin/env node
/**
 * gen-tile-pricing.mjs — emit the server's copy of the tile pricing model.
 *
 * The browser cannot be trusted to say what a tile costs. `/np/payment` still
 * takes `usd_amount` from the client (a pre-existing hole, documented in
 * documentation/backend.md), and the native-wallet path must not repeat it:
 * a user who can name their own price can buy a $76 Tokyo tile for $0.01.
 *
 * So the server needs `tileBasePrice()`. Rather than hand-porting 53 regions of
 * geography into Python and letting the two copies drift the first time someone
 * reprices a region, this generates the Python from src/lib/tiles.js — the same
 * module the map and the purchase panel import — plus a vector file so the
 * Python test can prove the port still agrees with the JS.
 *
 *   node scripts/gen-tile-pricing.mjs
 *
 * Writes:
 *   server/tile_pricing.py                     the port
 *   server/tests/tile_pricing_vectors.json     golden vectors from the JS
 *
 * Re-run it after ANY edit to GEO_REGIONS, MIN_TILE_PRICE_USD or tileBasePrice,
 * and commit both files. server/tests/test_tile_pricing.py fails if you don't.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const {
  GEO_REGIONS, MIN_TILE_PRICE_USD, PURCHASE_ZOOM, GRID_N,
  tileBasePrice, tileNW,
} = await import(resolve(ROOT, 'src/lib/tiles.js'))

// ── the Python port ──────────────────────────────────────────────────────────
const regionRows = GEO_REGIONS
  .map(r => `    (${r.lngMin}, ${r.lngMax}, ${r.latMin}, ${r.latMax}, ${r.base}, ${r.spread}),`)
  .join('\n')

const py = `"""
tile_pricing.py — what a tile costs, decided by the server.

GENERATED by scripts/gen-tile-pricing.mjs from src/lib/tiles.js. Do not edit by
hand: edit the JS and re-run the generator, or the map will quote one price and
the server will charge another.

Why this exists at all: the native-wallet purchase path (POST /chain/quote) must
price a tile without believing anything the browser says. The NOWPayments path
stores \`price_usd\` from a client-supplied field, so a crafted request buys any
tile for any amount; that hole is not repeated here.

Kept deliberately dependency-free so it imports under pytest with no app context.
"""

PURCHASE_ZOOM = ${PURCHASE_ZOOM}
GRID_N = ${GRID_N}
TOTAL_TILES = GRID_N * GRID_N
MIN_TILE_PRICE_USD = ${MIN_TILE_PRICE_USD}

# (lng_min, lng_max, lat_min, lat_max, base, spread) — first match wins, exactly
# as the JS loop does. Order is load-bearing: Tokyo metro sits inside Japan.
GEO_REGIONS = [
${regionRows}
]

# Ocean / unclassified, matching geoRegion()'s fallback.
DEFAULT_REGION = (12, 6)

import math


def tile_nw(tx: int, ty: int, z: int = PURCHASE_ZOOM):
    """Tile NW corner -> (lng, lat). Mirrors tileNW() in src/lib/tiles.js."""
    n = 2.0 ** z
    lng = tx / n * 360.0 - 180.0
    lat_rad = math.atan(math.sinh(math.pi * (1.0 - 2.0 * ty / n)))
    return lng, lat_rad * 180.0 / math.pi


def geo_region(lng: float, lat: float):
    """-> (base, spread). Mirrors geoRegion() in src/lib/tiles.js."""
    for lng_min, lng_max, lat_min, lat_max, base, spread in GEO_REGIONS:
        if lng_min <= lng < lng_max and lat_min <= lat < lat_max:
            return base, spread
    return DEFAULT_REGION


def tile_base_price(tx: int, ty: int) -> float:
    """
    USD price of a tile before market events. Mirrors tileBasePrice().

    The hash uses >>> 0 in JS (unsigned 32-bit); Python ints are unbounded, so
    the & 0xFFFFFFFF is what keeps the two in step on large coordinates.
    """
    lng, lat = tile_nw(tx, ty, PURCHASE_ZOOM)
    base, spread = geo_region(lng, lat)
    h = ((tx * 1619 + ty * 2971) & 0xFFFFFFFF) % 1000 / 1000.0
    price = base + h * spread
    return round(max(MIN_TILE_PRICE_USD, price) + 1e-9, 2)


def scarcity_multiplier(sold_count: int) -> float:
    """
    Tiles get more expensive as the world fills. Mirrors the client's
    \`1 + sold / TOTAL_TILES * 3\` in PurchasePanel.jsx.
    """
    return 1.0 + (max(0, sold_count) / TOTAL_TILES) * 3.0
`

// ── golden vectors, so the port can be proven rather than assumed ────────────
// A fixed spread: named cities, region seams, the grid corners, and a
// deterministic scatter. Seams matter most — an off-by-one in a `<` vs `<=`
// only shows up on a boundary.
const vectors = []
const push = (tx, ty, note) => {
  const { lng, lat } = tileNW(tx, ty, PURCHASE_ZOOM)
  vectors.push({ tx, ty, note, lng, lat, price: tileBasePrice(tx, ty) })
}

push(0, 0, 'grid NW corner')
push(GRID_N - 1, GRID_N - 1, 'grid SE corner')
push(GRID_N - 1, 0, 'grid NE corner')
push(0, GRID_N - 1, 'grid SW corner')
push(8192, 8192, 'null island')

// Region boundaries, both sides of every edge.
for (const r of GEO_REGIONS) {
  for (const [lng, lat] of [
    [r.lngMin, r.latMin], [r.lngMax, r.latMax],
    [r.lngMin - 0.01, r.latMin], [r.lngMax + 0.01, r.latMax],
    [(r.lngMin + r.lngMax) / 2, (r.latMin + r.latMax) / 2],
  ]) {
    const n = 2 ** PURCHASE_ZOOM
    const tx = Math.max(0, Math.min(n - 1, Math.floor((lng + 180) / 360 * n)))
    const s = Math.max(-0.9999, Math.min(0.9999, Math.sin(lat * Math.PI / 180)))
    const ty = Math.max(0, Math.min(n - 1,
      Math.floor((0.5 - Math.log((1 + s) / (1 - s)) / (4 * Math.PI)) * n)))
    push(tx, ty, `seam ${lng},${lat}`)
  }
}

// Deterministic scatter — no Math.random, so re-running never churns the file.
for (let i = 0; i < 400; i++) {
  const tx = (i * 1327 + 11) % GRID_N
  const ty = (i * 2711 + 7)  % GRID_N
  push(tx, ty, 'scatter')
}

mkdirSync(resolve(ROOT, 'server/tests'), { recursive: true })
writeFileSync(resolve(ROOT, 'server/tile_pricing.py'), py)
writeFileSync(
  resolve(ROOT, 'server/tests/tile_pricing_vectors.json'),
  JSON.stringify({
    generated_from: 'src/lib/tiles.js via scripts/gen-tile-pricing.mjs',
    min_tile_price_usd: MIN_TILE_PRICE_USD,
    purchase_zoom: PURCHASE_ZOOM,
    grid_n: GRID_N,
    vectors,
  }, null, 2) + '\n',
)

console.log(`✓ server/tile_pricing.py            (${GEO_REGIONS.length} regions)`)
console.log(`✓ server/tests/tile_pricing_vectors.json (${vectors.length} vectors)`)
