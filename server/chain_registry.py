# Canonical name -> key, for the `chain` column written on the blocks row.
BY_NAME = {c.name.lower(): c.key for c in CHAINS.values()}


def get_chain(key_or_name: str):
    """Look a chain up by key ('base') or canonical name ('Base'). None if unknown."""
    if not key_or_name:
        return None
    k = str(key_or_name).strip().lower()
    if k in CHAINS:
        return CHAINS[k]
    return CHAINS.get(BY_NAME.get(k, ""), None)


def payable_chains():
    return {k: c for k, c in CHAINS.items() if c.native_pay}
